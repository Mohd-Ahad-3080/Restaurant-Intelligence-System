"""Cost for two in US dollars (APPROXIMATE), for comparisons across countries.

Why: `avg_cost_for_two` is in each country's LOCAL currency, so raw costs cannot be compared across countries.
Two currency-free measures already exist and stay the default:
- `price_range` (1-4): Zomato's own band, comparable everywhere;
- `cost_pct_in_country` (model feature): the restaurant's cost percentile among restaurants of the same
  country and currency (0 = cheapest, 1 = dearest).
`avg_cost_for_two_usd` adds an approximate dollar value for charts that compare costs across countries.

Exchange rates: World Bank, World Development Indicators, indicator PA.NUS.FCRF "Official exchange rate
(LCU per US$, period average)", year 2017 (the last full year before the Kaggle dataset was published in 2018).
File: data/raw/worldbank_PA.NUS.FCRF_official_exchange_rate.csv, downloaded unchanged on 2026-11-19 from
https://api.worldbank.org/v2/en/indicator/PA.NUS.FCRF?downloadformat=csv (WDI last updated 2026-11-11).

Assumptions (stated in the docs): the rate is an annual average and Zomato menu prices were collected at an
unknown date around 2017-2018, so USD values are approximate. The currency label "Dollar($)" is used for four
countries (United States, Australia, Canada, Singapore); it is taken to mean each country's own dollar, so rates
are matched by COUNTRY, not by the currency label.
"""
from __future__ import annotations

import pandas as pd

from src import config

RATES_CSV = config.RAW_DIR / "worldbank_PA.NUS.FCRF_official_exchange_rate.csv"
RATE_YEAR = "2017"
SOURCE = ("World Bank, World Development Indicators, PA.NUS.FCRF Official exchange rate (LCU per US$, period "
          "average), 2017; downloaded 2026-11-19")

# dataset country name -> (World Bank ISO3 code, ISO 4217 currency code)
COUNTRY_CODES = {
    "India": ("IND", "INR"), "United States": ("USA", "USD"), "United Kingdom": ("GBR", "GBP"),
    "Brazil": ("BRA", "BRL"), "UAE": ("ARE", "AED"), "South Africa": ("ZAF", "ZAR"),
    "New Zealand": ("NZL", "NZD"), "Turkey": ("TUR", "TRY"), "Philippines": ("PHL", "PHP"),
    "Indonesia": ("IDN", "IDR"), "Qatar": ("QAT", "QAR"), "Sri Lanka": ("LKA", "LKR"),
    "Australia": ("AUS", "AUD"), "Canada": ("CAN", "CAD"), "Singapore": ("SGP", "SGD"),
}


def load_rates(path=RATES_CSV, year: str = RATE_YEAR) -> pd.DataFrame:
    """One row per dataset country: local currency units per US$ in `year`, read from the World Bank file."""
    wb = pd.read_csv(path, skiprows=4).set_index("Country Code")
    rows = []
    for country, (iso3, ccy) in COUNTRY_CODES.items():
        rate = wb.loc[iso3, year] if iso3 in wb.index else float("nan")
        rows.append({"country": country, "iso3": iso3, "currency_code": ccy,
                     "world_bank_country_name": wb.loc[iso3, "Country Name"] if iso3 in wb.index else None,
                     "lcu_per_usd": float(rate), "year": int(year), "source": SOURCE,
                     "note": "Approximate: annual average rate; menu price dates unknown (about 2017-2018)."})
    out = pd.DataFrame(rows)
    if out["lcu_per_usd"].isna().any() or (out["lcu_per_usd"] <= 0).any():
        raise ValueError(f"Missing or invalid exchange rate for: "
                         f"{out.loc[out['lcu_per_usd'].isna() | (out['lcu_per_usd'] <= 0), 'country'].tolist()}")
    return out


def add_cost_usd(df: pd.DataFrame, rates: pd.DataFrame | None = None) -> pd.DataFrame:
    """Add `avg_cost_for_two_usd` (approximate). Countries without a rate get a blank value, never a guess."""
    rates = load_rates() if rates is None else rates
    per_usd = df["country"].map(rates.set_index("country")["lcu_per_usd"])
    out = df.copy()
    out["avg_cost_for_two_usd"] = (out["avg_cost_for_two"].astype("Float64") / per_usd).round(2)
    return out


DOC = config.DOCS_DIR / "currency_and_costs.md"
RATES_OUT = config.PROCESSED_DIR / "exchange_rates_2017.csv"


def write_doc(clean: pd.DataFrame) -> pd.DataFrame:
    """Save the rate table and write docs/currency_and_costs.md (all numbers computed here)."""
    rates = load_rates()
    rates.to_csv(RATES_OUT, index=False)
    by = (clean.groupby(["country", "currency"])
          .agg(restaurants=("restaurant_id", "size"), with_cost=("avg_cost_for_two", "count"),
               median_cost_local=("avg_cost_for_two", "median"), median_cost_usd=("avg_cost_for_two_usd", "median"),
               mean_cost_usd=("avg_cost_for_two_usd", "mean"), mean_price_range=("price_range", "mean"))
          .reset_index().merge(rates[["country", "currency_code", "lcu_per_usd"]], on="country", how="left")
          .sort_values("restaurants", ascending=False))
    L = ["# Currency and Costs", "",
         "*Generated by `src/currency.py`. Rates are read from the stored World Bank file; nothing is typed in.*", "",
         "## Three ways to talk about price", "",
         "| measure | unit | comparable across countries? | used for |", "|---|---|---|---|",
         "| `price_range` (1-4) | Zomato price band | **Yes** (currency-free) | default for all cross-country "
         "comparisons, model feature |",
         "| `avg_cost_for_two` | local currency (see `currency`) | **No** | within one country only (e.g. India in "
         "INR), recommender budgets |",
         "| `cost_pct_in_country` | percentile 0-1 among restaurants of the same country and currency | **Yes** "
         "(relative position) | model feature; 0 = cheapest, 1 = dearest in that country |",
         "| `avg_cost_for_two_usd` | US dollars, **approximate** | Yes, roughly | charts that compare cost levels "
         "across countries |", "",
         "## Exchange rates used (approximate)", "",
         f"Source: {SOURCE}. Raw file stored unchanged: `data/raw/{RATES_CSV.name}`; table used: "
         f"`data/processed/{RATES_OUT.name}`.", "",
         "Why approximate: the rate is a 2017 annual average, and the date when Zomato listed each price is not in "
         "the data (the dataset was published in 2018). Use USD values for broad comparisons only.", "",
         "The currency label `Dollar($)` is used for the United States, Australia, Canada and Singapore. It is taken "
         "to be each country's own dollar, so rates are matched by country, not by currency label.", "",
         "| country | currency code | World Bank name | local units per US$ (2017) |", "|---|---|---|---|"]
    L += [f"| {r.country} | {r.currency_code} | {r.world_bank_country_name} | {r.lcu_per_usd:,.4f} |"
          for r in rates.itertuples(index=False)]
    L += ["", "## Cost for two by country", "",
          "| country | currency label in data | restaurants | with cost | median cost (local) | median cost (US$, "
          "approx.) | mean cost (US$, approx.) | mean price range |", "|---|---|---|---|---|---|---|---|"]
    L += [f"| {r.country} | {r.currency} | {r.restaurants:,} | {r.with_cost:,} | {r.median_cost_local:,.0f} | "
          f"{r.median_cost_usd:,.2f} | {r.mean_cost_usd:,.2f} | {r.mean_price_range:.2f} |"
          for r in by.itertuples(index=False)]
    L += ["", "Where costs are compared across countries, the US$ column is used (Excel Summary_By_Country, SQL "
          "Q17, Power BI and Tableau cost visuals). Within one country, local currency is used.", ""]
    DOC.write_text("\n".join(L), encoding="utf-8")
    return by
